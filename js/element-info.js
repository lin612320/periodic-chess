  /** 上标串还原成数字：'¹⁰' → 10，'⁶' → 6 */
  function unsup(s) {
    var digits = '';
    for (var i = 0; i < s.length; i++) {
      var v = '⁰¹²³⁴⁵⁶⁷⁸⁹'.indexOf(s.charAt(i));
      digits += (v >= 0 ? v : '');
    }
    return digits === '' ? 0 : Number(digits);
  }

  /** 生成能级排布：按 n 再按 s<p<d<f 排序，跟教材写法一致 */
  function configOf(z) {
    if (EXCEPTIONS[z]) return EXCEPTIONS[z];
    var left = z;
    var parts = [];
    for (var i = 0; i < ORDER.length && left > 0; i++) {
      var orb = ORDER[i][0];
      var cap = ORDER[i][1];
      var take = Math.min(cap, left);
      left -= take;
      if (take > 0) parts.push({ n: Number(orb[0]), l: 'spdf'.indexOf(orb[1]), text: orb + sup(take) });
    }
    parts.sort(function (a, b) {
      if (a.n !== b.n) return a.n - b.n;
      return a.l - b.l;
    });
    return parts.map(function (p) { return p.text; }).join(' ');
  }

  /** 电子层排布 K L M N ... */
  function shellsOf(z) {
    var shells = [0, 0, 0, 0, 0, 0, 0];
    var parts = configOf(z).split(' ');
    for (var i = 0; i < parts.length; i++) {
      var m = parts[i].match(/^(\d)([spdf])([⁰¹²³⁴⁵⁶⁷⁸⁹]+)$/);
      if (!m) continue;
      var n = Number(m[1]) - 1;
      if (n >= 0 && n < 7) shells[n] += unsup(m[3]);
    }
    while (shells.length && shells[shells.length - 1] === 0) shells.pop();
    return shells;
  }

  /** 最外层电子数 */
  function outerOf(z) {
    var s = shellsOf(z);
    return s.length ? s[s.length - 1] : 0;
  }

